// Канон форматирования JS/TS Хекслета это дефолты oxfmt, поэтому здесь лежит
// только список того, что oxfmt не трогает: YAML, JSON, CSS и markdown в ките
// ведут другие инструменты (docs/js-code-style.md). oxfmt находит файл сам, без
// --config, а в репозитории компонентов файл копируется как есть.
//
// Объект без `defineConfig`: его импорт потребовал бы пакет oxfmt в
// node_modules, а бинарь в ките ставит mise. Неверную опцию oxfmt ловит сам при
// загрузке (код выхода 1).
export default {
  ignorePatterns: [
    "**/*.yml",
    "**/*.yaml",
    "**/*.json",
    "**/*.jsonc",
    "**/*.css",
    "**/*.md",
    "**/*.toml",
    "**/npm-cache/**",
    "**/vendor/**",
    "**/dist/**",
    "**/build/**",
    "**/coverage/**",
    "**/.venv/**",
    "**/__snapshots__/**",
    // Сгенерированное не правится: файл перезаписывает кодогенератор, и правка
    // живёт до первого прогона. Каталог целиком, потому что hey-api кладёт рядом
    // с *.gen.ts ещё и index.ts, а i18next-cli пишет типы ресурсов в src/@types.
    "**/*.gen.ts",
    "**/src/types/handlers/**",
    "**/src/@types/**",
  ],
};
